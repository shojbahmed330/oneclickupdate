// scaffold_analytics — one call, wires up an analytics provider (PostHog /
// Plausible / GA4) in the generated app:
//   • src/lib/analytics.ts            — typed init + track() + identify() helpers
//   • src/hooks/useAnalyticsPageView.ts — auto page-view on route change
//   • Mounted in src/main.tsx (init) and AppRouter via the hook
// Reads the public key from a VITE_ env var the user must add. Returns the
// exact env-var names + where to get them.
import { tool } from "npm:ai@5.0.26";
import { z } from "npm:zod@3.23.8";
import type { DaytonaSandbox } from "../../_shared/daytona.ts";
import type { ToolCtx } from "../shared.ts";

type Provider = "posthog" | "plausible" | "ga4";

const PROVIDER_META: Record<Provider, {
  envVar: string;
  signupUrl: string;
  installDep: string | null;
  envHint: string;
}> = {
  posthog: {
    envVar: "VITE_POSTHOG_KEY",
    signupUrl: "https://posthog.com (Project → Settings → Project API Key)",
    installDep: "posthog-js",
    envHint: "Also set VITE_POSTHOG_HOST (e.g. https://us.i.posthog.com).",
  },
  plausible: {
    envVar: "VITE_PLAUSIBLE_DOMAIN",
    signupUrl: "https://plausible.io (Sites → your domain)",
    installDep: null, // script tag only
    envHint: "Set to your registered site domain, e.g. myapp.com.",
  },
  ga4: {
    envVar: "VITE_GA4_MEASUREMENT_ID",
    signupUrl: "https://analytics.google.com (Admin → Data Streams → Measurement ID, starts with G-)",
    installDep: null, // gtag script tag
    envHint: "Looks like G-XXXXXXXXXX.",
  },
};

function renderAnalyticsLib(provider: Provider): string {
  if (provider === "posthog") {
    return `// Auto-generated by scaffold_analytics — PostHog
import posthog from "posthog-js";

let inited = false;

export function initAnalytics() {
  if (inited) return;
  const key = import.meta.env.VITE_POSTHOG_KEY;
  const host = import.meta.env.VITE_POSTHOG_HOST ?? "https://us.i.posthog.com";
  if (!key) { console.warn("[analytics] VITE_POSTHOG_KEY missing — analytics disabled"); return; }
  posthog.init(key, { api_host: host, capture_pageview: false, persistence: "localStorage" });
  inited = true;
}

export function track(event: string, properties?: Record<string, unknown>) {
  if (!inited) return;
  posthog.capture(event, properties);
}

export function identify(userId: string, traits?: Record<string, unknown>) {
  if (!inited) return;
  posthog.identify(userId, traits);
}

export function trackPageView(path: string) {
  if (!inited) return;
  posthog.capture("$pageview", { $current_url: window.location.origin + path });
}
`;
  }
  if (provider === "plausible") {
    return `// Auto-generated by scaffold_analytics — Plausible (script-tag)
let inited = false;

export function initAnalytics() {
  if (inited) return;
  const domain = import.meta.env.VITE_PLAUSIBLE_DOMAIN;
  if (!domain) { console.warn("[analytics] VITE_PLAUSIBLE_DOMAIN missing — analytics disabled"); return; }
  const s = document.createElement("script");
  s.defer = true;
  s.dataset.domain = domain;
  s.src = "https://plausible.io/js/script.manual.js";
  document.head.appendChild(s);
  inited = true;
}

declare global {
  interface Window { plausible?: (event: string, opts?: { props?: Record<string, unknown>; u?: string }) => void; }
}

export function track(event: string, properties?: Record<string, unknown>) {
  window.plausible?.(event, { props: properties });
}

export function identify(_userId: string) { /* Plausible is cookieless — no identify */ }

export function trackPageView(path: string) {
  window.plausible?.("pageview", { u: window.location.origin + path });
}
`;
  }
  // ga4
  return `// Auto-generated by scaffold_analytics — GA4 (gtag)
let inited = false;

declare global {
  interface Window { dataLayer: unknown[]; gtag: (...args: unknown[]) => void; }
}

export function initAnalytics() {
  if (inited) return;
  const id = import.meta.env.VITE_GA4_MEASUREMENT_ID;
  if (!id) { console.warn("[analytics] VITE_GA4_MEASUREMENT_ID missing — analytics disabled"); return; }
  const s = document.createElement("script");
  s.async = true;
  s.src = \`https://www.googletagmanager.com/gtag/js?id=\${id}\`;
  document.head.appendChild(s);
  window.dataLayer = window.dataLayer || [];
  window.gtag = function gtag() { window.dataLayer.push(arguments); } as any;
  window.gtag("js", new Date());
  window.gtag("config", id, { send_page_view: false });
  inited = true;
}

export function track(event: string, properties?: Record<string, unknown>) {
  if (!inited) return;
  window.gtag("event", event, properties);
}

export function identify(userId: string, traits?: Record<string, unknown>) {
  if (!inited) return;
  window.gtag("set", "user_properties", { user_id: userId, ...traits });
}

export function trackPageView(path: string) {
  if (!inited) return;
  window.gtag("event", "page_view", { page_path: path });
}
`;
}

const PAGE_VIEW_HOOK = `// Auto page-view tracker — drop <AnalyticsPageView /> once in your router,
// OR call useAnalyticsPageView() in your top-level App component.
import { useEffect } from "react";
import { useLocation } from "react-router-dom";
import { trackPageView } from "@/lib/analytics";

export function useAnalyticsPageView() {
  const location = useLocation();
  useEffect(() => {
    trackPageView(location.pathname + location.search);
  }, [location.pathname, location.search]);
}

export function AnalyticsPageView() {
  useAnalyticsPageView();
  return null;
}
`;

export function makeScaffoldAnalyticsTools(sandbox: DaytonaSandbox, _ctx: ToolCtx, cwd: string) {
  return {
    scaffold_analytics: tool({
      description:
        "Wire up an analytics provider (posthog | plausible | ga4) in the generated app. " +
        "Writes src/lib/analytics.ts (init/track/identify/trackPageView) and " +
        "src/hooks/useAnalyticsPageView.ts (auto page-view on route change). " +
        "Returns the exact VITE_ env-var name(s) the user must add. " +
        "Agent must then: (a) call initAnalytics() in src/main.tsx, " +
        "(b) mount <AnalyticsPageView /> inside <BrowserRouter> in src/App.tsx, " +
        "(c) request the secret via request_secret with the returned env_var.",
      inputSchema: z.object({
        provider: z.enum(["posthog", "plausible", "ga4"]),
      }),
      execute: async ({ provider }) => {
        const meta = PROVIDER_META[provider as Provider];
        const libPath = "src/lib/analytics.ts";
        const hookPath = "src/hooks/useAnalyticsPageView.ts";
        const libCode = renderAnalyticsLib(provider as Provider);

        await sandbox.exec(`mkdir -p "${cwd}/src/lib" "${cwd}/src/hooks"`, cwd, 5);
        await sandbox.exec(
          `cat > "${cwd}/${libPath}" <<'EOF'\n${libCode}\nEOF`,
          cwd, 15,
        );
        await sandbox.exec(
          `cat > "${cwd}/${hookPath}" <<'EOF'\n${PAGE_VIEW_HOOK}\nEOF`,
          cwd, 15,
        );

        if (meta.installDep) {
          await sandbox.exec(`cd "${cwd}" && bun add ${meta.installDep}`, cwd, 90);
        }

        return {
          ok: true,
          provider,
          files_written: [libPath, hookPath],
          dep_installed: meta.installDep,
          env_var: meta.envVar,
          env_hint: meta.envHint,
          signup_url: meta.signupUrl,
          next_steps: [
            `1. In src/main.tsx, import { initAnalytics } from "@/lib/analytics" and call initAnalytics() BEFORE ReactDOM.createRoot.`,
            `2. In src/App.tsx, import { AnalyticsPageView } from "@/hooks/useAnalyticsPageView" and render <AnalyticsPageView /> inside <BrowserRouter>.`,
            `3. Call request_secret({ name: "${meta.envVar}", reason: "Analytics provider key" }).`,
            `4. (Optional) Use track('event_name', { ...props }) anywhere in the app.`,
          ],
        };
      },
    }),
  };
}
